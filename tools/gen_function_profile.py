#!/usr/bin/env python3
"""Generate a call-count profiler for ranges of recompiled guest functions.

    python3 tools/gen_function_profile.py OUT.cpp 82000000-83000000

Every generated function in the ranges gets an override that counts its calls,
then runs the original. With TABLETENNIS_PROFILE_DIR set, a background thread
writes the cumulative counts there every 10s (t00010.tsv, t00020.tsv, ...);
diff two snapshots to profile one stretch of play (tools/rank_hot_functions.py).
Functions src/ already overrides are skipped. Build it in with
-DTABLETENNIS_FUNCTION_TRACE_SOURCE=OUT.cpp; profiling only.
"""
import sys
from pathlib import Path

from gen_function_trace import parse_ranges, traceable


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    profiled = traceable(parse_ranges(sys.argv[2:]))
    lines = [
        '#include "generated/default/tabletennis_init.h"',
        "",
        "#include <atomic>",
        "#include <chrono>",
        "#include <cstdio>",
        "#include <cstdlib>",
        "#include <string>",
        "#include <thread>",
        "",
        "// Generated by tools/gen_function_profile.py; profiling only.",
        "namespace {",
        f"constexpr uint32_t kCount = {len(profiled)};",
        f"std::atomic<uint64_t> calls[kCount];",
        "const uint32_t addresses[kCount] = {",
    ]
    lines += [f"  0x{address:08X}," for address in profiled]
    lines += [
        "};",
        "",
        "void Snapshot(const std::string &dir, int seconds) {",
        "  char name[32];",
        '  std::snprintf(name, sizeof(name), "/t%05d.tsv", seconds);',
        "  const std::string path = dir + name;",
        "  FILE *file = std::fopen((path + \".tmp\").c_str(), \"w\");",
        "  if (file == nullptr) return;",
        "  for (uint32_t i = 0; i < kCount; ++i) {",
        "    const uint64_t count = calls[i].load(std::memory_order_relaxed);",
        "    if (count != 0) {",
        '      std::fprintf(file, "%08X\\t%llu\\n", addresses[i],',
        "                   static_cast<unsigned long long>(count));",
        "    }",
        "  }",
        "  std::fclose(file);",
        "  std::rename((path + \".tmp\").c_str(), path.c_str());",
        "}",
        "",
        "const bool started = [] {",
        '  const char *dir = std::getenv("TABLETENNIS_PROFILE_DIR");',
        "  if (dir == nullptr) return false;",
        "  std::thread([dir = std::string(dir)] {",
        "    for (int seconds = 10;; seconds += 10) {",
        "      std::this_thread::sleep_for(std::chrono::seconds(10));",
        "      Snapshot(dir, seconds);",
        "    }",
        "  }).detach();",
        "  return true;",
        "}();",
        "}  // namespace",
        "",
    ]
    for index, address in enumerate(profiled):
        lines += [f"extern \"C\" REX_FUNC(sub_{address:08X}) {{",
                  f"  calls[{index}].fetch_add(1, std::memory_order_relaxed);",
                  f"  __imp__sub_{address:08X}(ctx, base);",
                  "}"]
    Path(sys.argv[1]).write_text("\n".join(lines) + "\n")
    print(f"{len(profiled)} functions profiled into {sys.argv[1]}")


if __name__ == "__main__":
    main()
